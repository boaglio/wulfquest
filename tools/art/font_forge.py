def padded(rows):
    """Authored 6x7 into the declared 8x8 cell: one spare column, one spare row."""
    out = [row + "." * (CELL_W - GLYPH_W) for row in rows]
    out += ["." * CELL_W] * (CELL_H - GLYPH_H)
    return out


def main():
    for ch, rows in GLYPHS.items():
        if len(rows) != GLYPH_H or any(len(r) != GLYPH_W for r in rows):
            raise SystemExit("glyph '%s' is not %dx%d" % (ch, GLYPH_W, GLYPH_H))
        if any(set(r) - set(".#") for r in rows):
            raise SystemExit("glyph '%s' uses a character outside '.#'" % ch)

    font = json.loads(FONT.read_text())
    font["sets"]["big"] = {
        "name": "display-8x8",
        "size": {"w": CELL_W, "h": CELL_H},
        "advance": CELL_W,
        "lineHeight": CELL_H + 2,
        "legend": {".": -1, "#": 1},
        "glyphs": {ch: padded(rows) for ch, rows in GLYPHS.items()},
        "fallback": "?",
    }
    FONT.write_text(json.dumps(font, indent=2) + "\n")
    print("big: %d glyphs, %dx%d cell -> %s" % (len(GLYPHS), CELL_W, CELL_H, FONT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
